/// Lightweight app localization.
///
/// [tr] returns the selected language's translation for an English key, or the
/// English key itself when no translation exists (so the UI never shows empty
/// labels). Keys are the English strings used in the codebase, which keeps
/// call sites simple (Text(tr('Continue'))).
class AppStrings {
  AppStrings._();

  /// Persisted preference key for the selected language code ('en','hi',...).
  static const String prefKey = 'app_language';

  static final ValueNotifier<String> language = ValueNotifier<String>('en');

  static Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    language.value = prefs.getString(prefKey) ?? 'en';
  }

  static Future<void> setLanguage(String code) async {
    language.value = code;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(prefKey, code);
  }

  static bool get isHindi => language.value == 'hi';

  static String tr(String key) {
    if (language.value == 'hi') {
      return _hi[key] ?? key;
    }
    return key;
  }
}

